/**
 * Run folder lifecycle: `prepare` builds `~/Documents/staging-device-check/<TICKET>/<YYYY-MM-DD_HHMM>/` around the
 * installed workspace; `runTests` checks the tester's browserstack.yml and the minute budget, runs the BrowserStack
 * Node SDK there with the run context in env, and afterwards removes every credential from the folder.
 */
import { spawn as nodeSpawn } from 'node:child_process';
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { isMap, isSeq, parseDocument, YAMLSeq } from 'yaml';
import { checkYml, usedMinutes } from './bsyml.js';
import { evaluateArgFindings } from './evaluate-guard.js';
import { loadConfig } from './config.js';
import { stateDir } from './paths.js';
import { redactor } from './redact.js';
import { readGatePassword, type SecretDeps } from './secret.js';

export const TICKET = /^[A-Z][A-Z0-9]+-[0-9]+$/;
export const MINUTES_PER_TEST = 1.5;
export type Device = 'iphone' | 'android';
export type Mailbox = 'shared' | 'demo';
export type RunOptions = {
  devices?: Device[];
  confirmMinutes?: number;
  mailbox?: Mailbox;
  /** aborted from outside (Ctrl+C / SIGTERM in the CLI): the SDK is stopped and the run folder still cleaned */
  signal?: AbortSignal;
};

export type RunDeps = {
  env: NodeJS.ProcessEnv;
  secret: SecretDeps;
  fetchFn: typeof fetch;
  now: () => Date;
  /** number of tests in the run folder's spec (one project) */
  listTests: (dir: string) => Promise<number>;
  spawn: (
    cmd: string,
    args: string[],
    opts: { cwd: string; env: NodeJS.ProcessEnv; signal?: AbortSignal },
    onStdout: (chunk: string) => void,
    onStderr: (chunk: string) => void,
  ) => Promise<number>;
  out: (line: string) => void;
  err: (line: string) => void;
};

export type RunMeta = { ticket: string; host: string; createdAt: string; devices?: string[] };

const RUN_YML = '.browserstack.run.yml';
const TOKENS = '.run-tokens';
const pad = (n: number) => String(n).padStart(2, '0');

export const workspaceDir = (env: NodeJS.ProcessEnv) => join(stateDir(env), 'workspace');
export const outputRoot = (env: NodeJS.ProcessEnv) =>
  join(env.HOME || homedir(), 'Documents', 'staging-device-check');

export function validateTicket(ticket: string): void {
  if (!TICKET.test(ticket)) throw new Error(`Ticket „${ticket}“ hat nicht die Form ABC-123.`);
}

const PLAYWRIGHT_CONFIG = `// Generated by staging-device-check. Devices come from the BrowserStack SDK (browserstack.yml platforms).
import { defineConfig } from '@playwright/test';

export default defineConfig({
  testDir: '.',
  testMatch: '*.spec.ts',
  outputDir: './test-results',
  reporter: [['json', { outputFile: 'result.json' }], ['line']],
  retries: 0,
  // hasTouch: Android Chrome on BrowserStack refuses tap() without it
  use: { trace: 'off', video: 'off', screenshot: 'off', hasTouch: true },
});
`;

/** Creates the run folder and prints it. */
export function prepare(ticket: string, host: string, d: RunDeps): string {
  validateTicket(ticket);
  if (!/^[a-z0-9][a-z0-9.-]*\.[a-z0-9-]+$/.test(host))
    throw new Error(`„${host}“ ist kein App-Host.`);
  const ws = workspaceDir(d.env);
  if (!existsSync(join(ws, 'node_modules')) || !existsSync(join(ws, 'harness'))) {
    throw new Error(
      'Der Test-Arbeitsbereich ist nicht installiert — bitte zuerst „install-workspace“ ausführen.',
    );
  }
  const t = d.now();
  const stamp = `${t.getFullYear()}-${pad(t.getMonth() + 1)}-${pad(t.getDate())}_${pad(t.getHours())}${pad(t.getMinutes())}`;
  let dir = join(outputRoot(d.env), ticket, stamp);
  if (existsSync(dir)) dir = `${dir}${pad(t.getSeconds())}`;
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'playwright.config.ts'), PLAYWRIGHT_CONFIG);
  const meta: RunMeta = { ticket, host, createdAt: t.toISOString() };
  writeFileSync(join(dir, 'run.json'), `${JSON.stringify(meta, null, 2)}\n`);
  symlinkSync(join(ws, 'node_modules'), join(dir, 'node_modules'), 'dir');
  symlinkSync(join(ws, 'harness'), join(dir, 'harness'), 'dir');
  d.out(dir);
  return dir;
}

export const readMeta = (dir: string): RunMeta =>
  JSON.parse(readFileSync(join(dir, 'run.json'), 'utf8')) as RunMeta;

const isIos = (deviceName: string) => /^(iphone|ipad)/i.test(deviceName);

const SECRET_FIELD = /key|pass|secret|token/i;

type YmlPlan = {
  /** her yml already holds exactly the chosen platforms: the SDK reads it in place, no copy */
  inPlace: boolean;
  /** the narrowed copy (no credentials), when not in place */
  text: string;
  chosen: string[];
  /** values removed from browserstackLocalOptions, for the redactor */
  removed: string[];
};

/**
 * The first iPhone and/or the first Android phone of her yml (desktop platforms have no deviceName and are never
 * chosen). Her file is used in place when it holds exactly these platforms; otherwise a copy holds only them, named
 * after the run, without userName/accessKey and without key/password fields in browserstackLocalOptions.
 */
function planYml(source: string, devices: Device[], buildName: string): YmlPlan {
  // failsafe: every scalar stays the string it was written as (osVersion 13.10 stays 13.10); the platform nodes are
  // filtered, never rebuilt from plain values.
  const doc = parseDocument(readFileSync(source, 'utf8'), { schema: 'failsafe' });
  const platforms = doc.get('platforms', true);
  const all = isSeq(platforms) ? platforms.items : [];
  const maps = all.filter(isMap);
  const chosen = new YAMLSeq();
  const names: string[] = [];
  for (const want of devices) {
    const p = maps.find((x) => {
      const name = x.get('deviceName');
      return typeof name === 'string' && isIos(name) === (want === 'iphone');
    });
    if (!p)
      throw new Error(
        `In der browserstack.yml gibt es kein ${want === 'iphone' ? 'iPhone' : 'Android-Gerät'}.`,
      );
    chosen.items.push(p);
    names.push(String(p.get('deviceName')));
  }
  if (all.length === chosen.items.length)
    return { inPlace: true, text: '', chosen: names, removed: [] };
  doc.set('platforms', chosen);
  doc.set('buildName', buildName);
  // No copy ever carries credentials: the SDK gets them through the child's env.
  doc.delete('userName');
  doc.delete('accessKey');
  const removed: string[] = [];
  const local = doc.get('browserstackLocalOptions', true);
  if (isMap(local)) {
    // collected first: deleting while iterating the node's own items would skip entries
    const fields = local.items.map((pair) => ({
      k: String((pair.key as { value?: unknown })?.value ?? pair.key),
      v: (pair.value as { value?: unknown } | null)?.value,
    }));
    for (const { k, v } of fields) {
      if (!SECRET_FIELD.test(k)) continue;
      if (typeof v === 'string' && v) removed.push(v);
      local.delete(k);
    }
  }
  return { inPlace: false, text: doc.toString(), chosen: names, removed };
}

/** Line-buffered redaction for a child's output stream. */
function redactingStream(write: (line: string) => void, redact: (s: string) => string) {
  let buf = '';
  return {
    push: (chunk: string) => {
      buf += chunk;
      const lines = buf.split('\n');
      buf = lines.pop() ?? '';
      for (const l of lines) write(redact(l));
    },
    end: () => {
      if (buf) write(redact(buf));
      buf = '';
    },
  };
}

/**
 * Deletes the SDK's `log/`, the yml copy and the token list, then masks every secret (plus the tokens from the list)
 * in every remaining text file of the run folder. Symlinks (workspace) are never followed; binary files are skipped.
 */
export function cleanRunFolder(dir: string, secrets: string[]): void {
  const tokenFile = join(dir, TOKENS);
  const tokens = existsSync(tokenFile)
    ? readFileSync(tokenFile, 'utf8')
        .split('\n')
        .map((s) => s.trim())
        .filter(Boolean)
    : [];
  rmSync(tokenFile, { force: true });
  rmSync(join(dir, 'log'), { recursive: true, force: true });
  rmSync(join(dir, RUN_YML), { force: true });
  const redact = redactor([...secrets, ...tokens]);
  const walk = (p: string) => {
    for (const name of readdirSync(p)) {
      const f = join(p, name);
      const st = lstatSync(f);
      if (st.isSymbolicLink()) continue;
      if (st.isDirectory()) walk(f);
      else if (st.isFile()) {
        const buf = readFileSync(f);
        if (buf.subarray(0, 8192).includes(0)) continue; // binary
        const text = buf.toString('utf8');
        const masked = redact(text);
        if (masked !== text) writeFileSync(f, masked);
      }
    }
  };
  walk(dir);
}

/** The spec files of the run folder, checked for evaluate arguments iOS would drop. */
function specFindings(dir: string): string[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.spec.ts'))
    .flatMap((f) => {
      try {
        return evaluateArgFindings(readFileSync(join(dir, f), 'utf8'), f);
      } catch (e) {
        return [`${f} (nicht lesbar: ${(e as Error).message.split('\n')[0]})`];
      }
    });
}

const NOT_STARTED = /UmgebungNichtGestartet|Umgebung nicht gestartet/;

const minutesText = (m: number) => `${Math.round(m * 10) / 10}`.replace('.', ',');

export async function runTests(dir: string, opts: RunOptions, d: RunDeps): Promise<number> {
  // a copy left by a crashed run goes first, whatever happens next
  rmSync(join(dir, RUN_YML), { force: true });
  const meta = readMeta(dir);
  validateTicket(meta.ticket);
  const unsafe = specFindings(dir);
  if (unsafe.length) {
    d.err(
      `Der Test übergibt page.evaluate (oder $eval, waitForFunction …) ein Argument, das auf dem iPhone verloren geht: ${unsafe.join(', ')}. ` +
        'Bitte evaluateWith(page, fn, arg) aus der Harness verwenden. Der Lauf startet nicht.',
    );
    return 1;
  }
  const config = loadConfig(d.env);
  if (!config) {
    d.err('Keine Einstellungen gefunden — bitte zuerst das Setup ausführen.');
    return 1;
  }
  const yml = checkYml(config.browserstackYml, d.env);
  for (const w of yml.warnings) d.err(`Hinweis: ${w}`);
  if (!yml.ok) {
    for (const e of yml.errors) d.err(`Fehler: ${e}`);
    d.err('Der Lauf startet nicht, bis die browserstack.yml stimmt.');
    return 1;
  }
  const [user, key] = yml.secretsForRedaction;
  const gate = readGatePassword(d.secret);
  // Default: one iPhone and one Android phone from her yml's platforms.
  const devices: Device[] = opts.devices?.length ? opts.devices : ['iphone', 'android'];
  const deviceCount = devices.length;
  const t = d.now();
  const buildName = `${meta.ticket} ${t.getFullYear()}-${pad(t.getMonth() + 1)}-${pad(t.getDate())}`;
  const plan = planYml(config.browserstackYml, devices, buildName);
  const secrets = [...yml.secretsForRedaction, ...plan.removed, ...(gate ? [gate] : [])];
  const redact = redactor(secrets);

  const tests = await d.listTests(dir);
  if (!Number.isFinite(tests) || tests < 1) {
    d.err('Keine Tests im Run-Ordner gefunden — zuerst eine *.spec.ts anlegen.');
    return 1;
  }
  const estimate = tests * deviceCount * MINUTES_PER_TEST;
  const used = await usedMinutes(user, key, d.fetchFn);
  const remaining = used === null ? null : config.planMinutes - used;
  d.out(
    `Geschätzt: ${tests} Test(s) × ${deviceCount} Gerät(e) × ${minutesText(MINUTES_PER_TEST)} Min ≈ ${minutesText(estimate)} Min; ` +
      (remaining === null
        ? 'Restminuten unbekannt.'
        : `übrig ≈ ${minutesText(remaining)} von ${config.planMinutes} Min (geschätzt).`),
  );
  const confirmed = (opts.confirmMinutes ?? 0) >= estimate;
  if (remaining === null && !confirmed) {
    d.err(
      `Die Restminuten bei BrowserStack sind nicht abrufbar; geschätzt braucht der Lauf ${minutesText(estimate)} Min. ` +
        `Zum Bestätigen mit --confirm-minutes ${Math.ceil(estimate)} erneut starten.`,
    );
    return 1;
  }
  if (estimate > config.perRunMinutes && !confirmed) {
    d.err(
      `Der Lauf braucht geschätzt ${minutesText(estimate)} Min, mehr als die ${config.perRunMinutes} Min pro Lauf. ` +
        `Zum Bestätigen mit --confirm-minutes ${Math.ceil(estimate)} erneut starten.`,
    );
    return 1;
  }
  if (remaining !== null && estimate > remaining) {
    d.err(
      `Geschätzt ${minutesText(estimate)} Min, aber nur noch ≈ ${minutesText(remaining)} Min übrig (geschätzt). Der Lauf startet nicht.`,
    );
    return 1;
  }
  if (remaining !== null && remaining - estimate < config.warnBelowMinutes) {
    d.err(
      `Hinweis: Nach dem Lauf bleiben geschätzt nur ≈ ${minutesText(remaining - estimate)} Min übrig.`,
    );
  }

  const ymlCopy = join(dir, RUN_YML);
  let code = 1;
  try {
    const chosen = plan.chosen;
    let configFile = config.browserstackYml;
    const credentials: Record<string, string> = {};
    if (!plan.inPlace) {
      writeFileSync(ymlCopy, plan.text, { mode: 0o600 });
      configFile = ymlCopy;
      // the copy holds no credentials; the SDK reads its documented env variables, read here from her yml
      credentials.BROWSERSTACK_USERNAME = user;
      credentials.BROWSERSTACK_ACCESS_KEY = key;
    }
    writeFileSync(
      join(dir, 'run.json'),
      `${JSON.stringify({ ...meta, devices: chosen }, null, 2)}\n`,
    );
    // The harness throws UmgebungNichtGestartet on the first test; the remaining tests would open device sessions
    // against a host that shows no app, so the SDK is stopped right there.
    const stop = new AbortController();
    let notStarted = false;
    const outside = () => stop.abort();
    if (opts.signal?.aborted) stop.abort();
    else opts.signal?.addEventListener('abort', outside, { once: true });
    const watch = (write: (line: string) => void) => (line: string) => {
      if (NOT_STARTED.test(line)) {
        notStarted = true;
        stop.abort();
      }
      write(line);
    };
    const out = redactingStream(watch(d.out), redact);
    const err = redactingStream(watch(d.err), redact);
    code = await d.spawn(
      join(dir, 'node_modules', '.bin', 'browserstack-node-sdk'),
      ['playwright', 'test'],
      {
        cwd: dir,
        env: {
          ...d.env,
          ...credentials,
          // the SDK's documented config-file and build-name variables
          BROWSERSTACK_CONFIG_FILE: configFile,
          BROWSERSTACK_BUILD_NAME: buildName,
          SDC_HOST: meta.host,
          SDC_RUN_DIR: dir,
          SDC_TICKET: meta.ticket,
          SDC_MAILBOX: opts.mailbox ?? 'shared',
        },
        signal: stop.signal,
      },
      out.push,
      err.push,
    );
    out.end();
    err.end();
    opts.signal?.removeEventListener('abort', outside);
    if (stop.signal.aborted) {
      d.err(
        notStarted
          ? `Lauf abgebrochen: ${meta.host} zeigt nicht die App (Umgebung nicht gestartet). Die übrigen Tests wurden nicht gestartet.`
          : 'Lauf abgebrochen (Strg+C oder Signal). Die übrigen Tests wurden nicht gestartet; der Run-Ordner ist aufgeräumt.',
      );
      if (code === 0) code = 1;
    }
  } finally {
    cleanRunFolder(dir, secrets);
  }
  const after = await usedMinutes(user, key, d.fetchFn);
  if (after !== null && used !== null) {
    d.out(
      `Verbraucht ≈ ${minutesText(after - used)} Min, übrig ≈ ${minutesText(config.planMinutes - after)} Min (geschätzt).`,
    );
  }
  return code;
}

/** Real process boundary for the CLI. */
export const realSpawn: RunDeps['spawn'] = (cmd, args, opts, onStdout, onStderr) =>
  new Promise((resolve) => {
    const child = nodeSpawn(cmd, args, {
      cwd: opts.cwd,
      env: opts.env,
      stdio: ['ignore', 'pipe', 'pipe'],
      signal: opts.signal,
    });
    child.stdout.setEncoding('utf8').on('data', onStdout);
    child.stderr.setEncoding('utf8').on('data', onStderr);
    child.on('error', (e) => {
      if (e.name === 'AbortError') return; // stopped on purpose; 'close' follows
      onStderr(`${e.message}\n`);
      resolve(127);
    });
    child.on('close', (c) => resolve(c ?? 1));
  });

/** Counts the tests with `playwright test --list --reporter=json` (one local project; no BrowserStack). */
export const realListTests =
  (spawn: RunDeps['spawn'], env: NodeJS.ProcessEnv) => async (dir: string) => {
    let json = '';
    const code = await spawn(
      join(dir, 'node_modules', '.bin', 'playwright'),
      ['test', '--list', '--reporter=json'],
      { cwd: dir, env },
      (c) => (json += c),
      () => {},
    );
    if (code !== 0)
      throw new Error(
        'Die Tests im Run-Ordner lassen sich nicht auflisten (Syntaxfehler im Test?).',
      );
    type S = { specs?: Array<{ tests?: unknown[] }>; suites?: S[] };
    const count = (s: S): number =>
      (s.specs ?? []).reduce((n, sp) => n + (sp.tests?.length ?? 0), 0) +
      (s.suites ?? []).reduce((n, x) => n + count(x), 0);
    return (JSON.parse(json) as { suites?: S[] }).suites?.reduce((n, s) => n + count(s), 0) ?? 0;
  };
